/**
 * Traduz um código ICAO para o nome legível.
 * Se o código não for encontrado, retorna o próprio código.
 */
export function traduzirIcao(codigo: string | null | undefined): string {
  if (!codigo) return "";
  const key = codigo.toUpperCase().trim();
  return icaoTipos[key] ?? key;
}
